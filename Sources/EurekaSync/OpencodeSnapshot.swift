import EurekaStore
import Foundation

/// opencode sessions live only in one live WAL SQLite database; a naive file copy may get
/// an inconsistent snapshot → use VACUUM INTO to produce a transactionally consistent snapshot
/// file, then upload it.
/// (VACUUM INTO can run from a read-only connection since SQLite 3.27; macOS 14's system library
/// is far newer.)
public enum OpencodeSnapshot {
    /// Change fingerprint: size = db + db-wal bytes combined, mtime = the larger of the two.
    /// Compared with sync_state(path = dbPath); if unchanged the whole step is skipped (no VACUUM).
    public static func fingerprint(dbPath: URL) -> (size: Int64, mtime: Double)? {
        let fm = FileManager.default
        guard fm.fileExists(atPath: dbPath.path) else { return nil }
        var totalSize: Int64 = 0
        var latestMtime: Double = 0
        for url in [dbPath, URL(fileURLWithPath: dbPath.path + "-wal")] {
            guard let attrs = try? fm.attributesOfItem(atPath: url.path) else { continue }
            totalSize += (attrs[.size] as? Int64) ?? 0
            let mtime = (attrs[.modificationDate] as? Date)?.timeIntervalSince1970 ?? 0
            latestMtime = max(latestMtime, mtime)
        }
        return (totalSize, latestMtime)
    }

    /// Opens read-only → VACUUM INTO a temp snapshot; returns the snapshot URL, and the caller
    /// deletes it after uploading
    public static func snapshot(dbPath: URL, to tempDir: URL) throws -> URL {
        let target = tempDir.appendingPathComponent(
            "opencode-snapshot-\(Int(Date().timeIntervalSince1970)).db")
        try? FileManager.default.removeItem(at: target)
        try FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
        let db = try SQLiteDB(path: dbPath.path, readOnly: true)
        // The path is generated by us (temp dir + timestamp); escaping single quotes is purely
        // defensive
        let escaped = target.path.replacingOccurrences(of: "'", with: "''")
        try db.execute("VACUUM INTO '\(escaped)'")
        return target
    }
}
